// 2.6 Types bij variabelen — voorbeeld uit Het Groenhuis, deel I
//
// Een type schrijf je achter de naam, na een dubbelpunt.
//
// Opbouw van dit bestand:
// console.log(…) toont: 0.1 + 0.2
// console.log(…) toont: 0.1 + 0.2 === 0.3
// console.log(…) toont: 10 + 20
//
// In de cursus heet dit bestand domein/src/proef.ts.
// Zet het bestand als src/proef.ts in groenhuis/domein, open daar een terminal en typ:
//     node src/proef.ts

console.log(0.1 + 0.2);
console.log(0.1 + 0.2 === 0.3);
console.log(10 + 20);

// Uitvoer van `node src/proef.ts`:
// 0.30000000000000004
// false
// 30
